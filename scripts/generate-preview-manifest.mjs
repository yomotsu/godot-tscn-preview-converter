import { readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
async function scenes(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map(entry => entry.isDirectory() ? scenes(path.join(directory, entry.name)) : entry.name.endsWith('.tscn') ? [path.join(directory, entry.name)] : []));
  return files.flat().sort();
}
const files = (await Promise.all([
  scenes(path.join(root, 'examples/assets/ExplosionFX/effects')),
])).flat().sort();
const effects = files.map(file => {
  const relative = path.relative(root, file).split(path.sep).join('/');
  const id = path.basename(file, '.tscn');
  return { id, name: ({vfx_ground_explosion_01:'地上爆発',vfx_air_explosion_01:'空中爆発',vfx_nuke_explosion_01:'核爆発'})[id] ?? id.replace(/^vfx_/, '').replaceAll('_', ' '), path: 'res://assets/BinbunVFX_Vol2/' + relative };
});
await writeFile(path.join(root, 'src/app/effects.js'), '// Generated by scripts/generate-preview-manifest.mjs\nexport const effects = ' + JSON.stringify(effects, null, 2) + ';\n');
console.log(`Preview catalog: ${effects.length} effects`);
